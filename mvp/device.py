"""设备管理 —— Phase 4 软件层（ESP32-S3）
硬件采购需用户确认，本模块实现设备绑定、OTA接口、户外模式逻辑。"""
from __future__ import annotations
from datetime import datetime
def _now():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

class DeviceManager:
    def __init__(self, conn):
        self.conn = conn
        c = conn.cursor()
        pg = "psycopg" in type(conn).__module__
        if pg:
            c.execute("""CREATE TABLE IF NOT EXISTS device (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                device_id TEXT NOT NULL UNIQUE, child_id TEXT,
                bound_at TEXT, last_seen TEXT)""")
        else:
            c.execute("""CREATE TABLE IF NOT EXISTS device (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                device_id TEXT NOT NULL UNIQUE, child_id TEXT,
                bound_at TEXT, last_seen TEXT)""")
        conn.commit()
        self._pg = pg
    def bind(self, device_id, child_id):
        c = self.conn.cursor()
        ph = "%s,%s,%s" if self._pg else "?,?,?"
        c.execute(f"INSERT INTO device (device_id,child_id,bound_at) VALUES ({ph}) ON CONFLICT (device_id) DO UPDATE SET child_id=excluded.child_id",
                  (device_id, child_id, _now()))
        self.conn.commit()
    def heartbeat(self, device_id):
        c = self.conn.cursor()
        ph = "%s" if self._pg else "?"
        c.execute(f"UPDATE device SET last_seen={ph} WHERE device_id={ph}", (_now(), device_id))
        self.conn.commit()
    def ota_push(self, device_id, version):
        """OTA 推送（接口，实际下发由设备端实现）。"""
        return {"device_id": device_id, "version": version, "status": "queued", "at": _now()}

class OutdoorMode:
    """户外模式：现实探索而非室内课程。"""
    PROMPTS = [
        "看看周围有几种颜色？",
        "你发现了什么奇怪的东西？",
        "听听看，有几种声音？",
        "找找看，哪里有圆形的东西？",
        "今天在外面试着说3句英语吧",
    ]
    def __init__(self): self._idx = 0
    def next_invite(self):
        p = self.PROMPTS[self._idx % len(self.PROMPTS)]
        self._idx += 1
        return p
