"""成长事件系统 V3.0 Phase 0核心工程1 - xAPI形状"""
from __future__ import annotations
import re
from datetime import datetime
VALID_VERBS = {"attempted","completed","expressed","answered","asked","observed","played","read","watched","transferred","refused","paused"}
VALID_EVIDENCE = {"L1","L2","L3"}
_SCORE_RE = re.compile(r"(\d+\s*分|得分\s*\d+|score\s*[:=]?\s*\d+)", re.IGNORECASE)
INSUFFICIENT_INFO = "信息不足"
def _now():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")
class GrowthEventStore:
    def __init__(self, conn):
        self.conn = conn
        self._ensure()
    def _is_pg(self):
        return "psycopg" in type(self.conn).__module__
    def _ensure(self):
        c = self.conn.cursor()
        if self._is_pg():
            c.execute("""CREATE TABLE IF NOT EXISTS learning_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                actor TEXT NOT NULL, verb TEXT NOT NULL,
                object_id TEXT NOT NULL, object_type TEXT NOT NULL DEFAULT 'activity',
                result TEXT, confidence REAL NOT NULL DEFAULT 0.5,
                evidence_level TEXT NOT NULL DEFAULT 'L2', domain TEXT,
                occurred_at TEXT NOT NULL,
                stored_at TEXT NOT NULL DEFAULT (to_char(now(),'YYYY-MM-DD HH24:MI:SS')))""")
        else:
            c.execute("""CREATE TABLE IF NOT EXISTS learning_events (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                actor TEXT NOT NULL, verb TEXT NOT NULL,
                object_id TEXT NOT NULL, object_type TEXT NOT NULL DEFAULT 'activity',
                result TEXT, confidence REAL NOT NULL DEFAULT 0.5,
                evidence_level TEXT NOT NULL DEFAULT 'L2', domain TEXT,
                occurred_at TEXT NOT NULL,
                stored_at TEXT NOT NULL DEFAULT (datetime('now','localtime')))""")
        self.conn.commit()
    def record_event(self, *, actor, verb, object_id, object_type="activity", result="", confidence=0.5, evidence_level="L2", domain=""):
        if not actor or not actor.strip(): raise ValueError("actor不能为空")
        if verb not in VALID_VERBS: raise ValueError(f"verb非法: {verb}")
        if evidence_level not in VALID_EVIDENCE: raise ValueError(f"evidence_level非法")
        if not (0 <= confidence <= 1): raise ValueError("confidence须0-1")
        if result and _SCORE_RE.search(result): raise ValueError("禁止数字评分")
        if not result or not result.strip():
            result = INSUFFICIENT_INFO; evidence_level = "L1"
        c = self.conn.cursor()
        if self._is_pg():
            c.execute("INSERT INTO learning_events (actor,verb,object_id,object_type,result,confidence,evidence_level,domain,occurred_at) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id",
                (actor,verb,object_id,object_type,result,confidence,evidence_level,domain,_now()))
            eid = c.fetchone()[0]
        else:
            c.execute("INSERT INTO learning_events (actor,verb,object_id,object_type,result,confidence,evidence_level,domain,occurred_at) VALUES (?,?,?,?,?,?,?,?,?)",
                (actor,verb,object_id,object_type,result,confidence,evidence_level,domain,_now()))
            eid = c.lastrowid
        self.conn.commit()
        return eid
    def get_events(self, actor, domain="", days=30):
        c = self.conn.cursor()
        ph = "%s" if self._is_pg() else "?"
        c.execute(f"SELECT id,actor,verb,object_id,object_type,result,confidence,evidence_level,domain,occurred_at,stored_at FROM learning_events WHERE actor={ph} AND ({ph}='' OR domain={ph}) ORDER BY occurred_at DESC LIMIT 200",
            (actor, domain, domain))
        cols = [d[0] for d in c.description]
        out = []
        for row in c.fetchall():
            e = dict(zip(cols, row))
            if e["evidence_level"]=="L3" and not e["result"].startswith("[推测]"):
                e["result"] = "[推测]" + e["result"]
            out.append(e)
        return out
