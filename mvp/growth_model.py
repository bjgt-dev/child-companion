"""成长模型 V3.0 Phase 0核心工程2 - 描述性,禁止打分"""
from __future__ import annotations
import re
from datetime import datetime
DOMAINS = ["语言沟通","数学逻辑","科学探索","执行功能","创造力","社交情绪","身体动作","生活能力","自主学习","价值观"]
_SCORE_RE = re.compile(r"(\d+\s*分|得分\s*\d+|score\s*[:=]?\s*\d+)", re.IGNORECASE)
def _now():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")
def _no_score(t):
    if t and _SCORE_RE.search(t): raise ValueError(f"禁止数字评分: {t[:40]}")
class GrowthModel:
    def __init__(self, conn):
        self.conn = conn
        self._ensure()
    def _is_pg(self):
        return "psycopg" in type(self.conn).__module__
    def _ensure(self):
        c = self.conn.cursor()
        if self._is_pg():
            c.execute("""CREATE TABLE IF NOT EXISTS growth_domains (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                child_id TEXT NOT NULL, domain TEXT NOT NULL,
                status_description TEXT NOT NULL DEFAULT '',
                last_updated TEXT NOT NULL DEFAULT (to_char(now(),'YYYY-MM-DD HH24:MI:SS')),
                UNIQUE (child_id, domain))""")
        else:
            c.execute("""CREATE TABLE IF NOT EXISTS growth_domains (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                child_id TEXT NOT NULL, domain TEXT NOT NULL,
                status_description TEXT NOT NULL DEFAULT '',
                last_updated TEXT NOT NULL DEFAULT (datetime('now','localtime')),
                UNIQUE (child_id, domain))""")
        self.conn.commit()
    def update_domain(self, child_id, domain, description):
        if domain not in DOMAINS: raise ValueError(f"domain非法: {domain}")
        _no_score(description)
        c = self.conn.cursor()
        if self._is_pg():
            c.execute("INSERT INTO growth_domains (child_id,domain,status_description,last_updated) VALUES (%s,%s,%s,%s) ON CONFLICT (child_id,domain) DO UPDATE SET status_description=EXCLUDED.status_description,last_updated=EXCLUDED.last_updated",
                (child_id,domain,description,_now()))
        else:
            c.execute("INSERT INTO growth_domains (child_id,domain,status_description,last_updated) VALUES (?,?,?,?) ON CONFLICT (child_id,domain) DO UPDATE SET status_description=excluded.status_description,last_updated=excluded.last_updated",
                (child_id,domain,description,_now()))
        self.conn.commit()
    def get_growth_snapshot(self, child_id):
        c = self.conn.cursor()
        ph = "%s" if self._is_pg() else "?"
        c.execute(f"SELECT domain,status_description FROM growth_domains WHERE child_id={ph}", (child_id,))
        snap = {}
        for d, desc in c.fetchall():
            _no_score(desc)
            snap[d] = desc or "暂无记录"
        for d in DOMAINS:
            snap.setdefault(d, "暂无记录")
        return snap
