"""长期记忆 + 间隔复习 + 成长轨迹 —— Phase 2"""
from __future__ import annotations
from datetime import datetime, timedelta

def _now():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

class Memory:
    """长期记忆：store/recall。"""
    def __init__(self, conn):
        self.conn = conn
        c = conn.cursor()
        pg = "psycopg" in type(conn).__module__
        if pg:
            c.execute("""CREATE TABLE IF NOT EXISTS memory (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                child_id TEXT NOT NULL, memory_type TEXT NOT NULL, content TEXT NOT NULL,
                importance REAL NOT NULL DEFAULT 0.5,
                created_at TEXT NOT NULL DEFAULT (to_char(now(),'YYYY-MM-DD HH24:MI:SS')),
                last_accessed TEXT)""")
        else:
            c.execute("""CREATE TABLE IF NOT EXISTS memory (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                child_id TEXT NOT NULL, memory_type TEXT NOT NULL, content TEXT NOT NULL,
                importance REAL NOT NULL DEFAULT 0.5,
                created_at TEXT NOT NULL DEFAULT (datetime('now','localtime')),
                last_accessed TEXT)""")
        conn.commit()
        self._pg = pg
    def store(self, child_id, memory_type, content, importance=0.5):
        c = self.conn.cursor()
        ph = "%s,%s,%s,%s" if self._pg else "?,?,?,?"
        c.execute(f"INSERT INTO memory (child_id,memory_type,content,importance) VALUES ({ph})",
                  (child_id, memory_type, content, importance))
        self.conn.commit()
    def recall(self, child_id, query="", top_k=3):
        c = self.conn.cursor()
        ph = "%s" if self._pg else "?"
        c.execute(f"SELECT content,importance,memory_type FROM memory WHERE child_id={ph} ORDER BY importance DESC LIMIT {top_k}",
                  (child_id,))
        rows = c.fetchall()
        # 简单相关度：query 关键词命中加权
        scored = []
        for content, imp, mt in rows:
            score = imp
            if query and query in content: score += 0.3
            scored.append((score, content, mt))
        scored.sort(reverse=True)
        return [{"content": c2, "type": mt} for _, c2, mt in scored[:top_k]]

class ReviewScheduler:
    """间隔复习：1天→3天→7天→14天。"""
    INTERVALS = [1, 3, 7, 14]
    def next_reviews(self, learned_at: str):
        base = datetime.strptime(learned_at, "%Y-%m-%d %H:%M:%S")
        return [(base + timedelta(days=d)).strftime("%Y-%m-%d") for d in self.INTERVALS]

def growth_report(growth_model, child_id):
    """成长轨迹报告：描述性，无数字评分。"""
    snap = growth_model.get_growth_snapshot(child_id)
    lines = [f"## {child_id} 成长轨迹"]
    for domain, desc in snap.items():
        if desc != "暂无记录":
            lines.append(f"- {domain}：{desc}")
    return "\n".join(lines)
