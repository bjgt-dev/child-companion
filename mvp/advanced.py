"""高级 Agent —— Phase 5：Research管线 + Learning Scientist + Child Dev + Parent Copilot v2"""
from __future__ import annotations
from datetime import datetime
def _now():
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

class ResearchPipeline:
    """研究更新管线：搜索→分级→审核→策略候选。"""
    GRADES = {"A": "多项高质量研究", "B": "较好单项研究", "C": "专家观点", "D": "营销文章"}
    def __init__(self, conn):
        self.conn = conn
        c = conn.cursor()
        pg = "psycopg" in type(conn).__module__
        if pg:
            c.execute("""CREATE TABLE IF NOT EXISTS research_evidence (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL, source TEXT, evidence_grade TEXT NOT NULL DEFAULT 'C',
                summary TEXT, reviewed_at TEXT)""")
        else:
            c.execute("""CREATE TABLE IF NOT EXISTS research_evidence (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                title TEXT NOT NULL, source TEXT, evidence_grade TEXT NOT NULL DEFAULT 'C',
                summary TEXT, reviewed_at TEXT)""")
        conn.commit()
        self._pg = pg
    def add(self, title, source="", grade="C", summary=""):
        if grade not in self.GRADES: raise ValueError(f"grade非法: {grade}")
        c = self.conn.cursor()
        ph = "%s,%s,%s,%s" if self._pg else "?,?,?,?"
        c.execute(f"INSERT INTO research_evidence (title,source,evidence_grade,summary) VALUES ({ph})",
                  (title, source, grade, summary))
        self.conn.commit()
    def candidates(self, min_grade="B"):
        """返回达到最低等级的研究（A/B 可进策略候选）。"""
        order = {"A": 0, "B": 1, "C": 2, "D": 3}
        c = self.conn.cursor()
        c.execute("SELECT title,evidence_grade,summary FROM research_evidence")
        return [r for r in c.fetchall() if order.get(r[1], 9) <= order[min_grade]]

class LearningScientist:
    """教研员：分析事件，提策略建议（不直接改策略）。"""
    def analyze(self, events: list) -> dict:
        total = len(events)
        l3 = sum(1 for e in events if e.get("evidence_level") == "L3")
        return {
            "total_events": total,
            "l3_ratio": round(l3 / total, 2) if total else 0,
            "suggestion": "L3推测比例过高，建议增加直接观察" if total and l3 / total > 0.3 else "证据结构健康",
            "at": _now(),
        }

class ChildDevMonitor:
    """发展监测：10领域均衡性，长期忽略告警。"""
    def check(self, snapshot: dict, days_since: dict) -> list:
        alerts = []
        for domain, desc in snapshot.items():
            if desc == "暂无记录" and days_since.get(domain, 0) > 30:
                alerts.append(f"{domain}已{days_since[domain]}天无记录，建议关注")
        return alerts

class ParentCopilotV2:
    """家长助手 v2：周报 + 月度深度报告。"""
    def weekly(self, child_id, interests: list, growth: dict) -> str:
        lines = [f"# {child_id} 本周成长摘要"]
        if interests: lines.append(f"## 兴趣：{', '.join(interests[:3])}")
        lines.append("## 能力进展：")
        for d, desc in growth.items():
            if desc != "暂无记录": lines.append(f"- {d}：{desc}")
        lines.append("## 建议活动：户外探索1次 + 亲子阅读2次")
        lines.append("## 家长可做的事：多问开放性问题，少给标准答案")
        return "\n".join(lines)
